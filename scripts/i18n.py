"""The framework's translations, one source for C and Python.

i18n/LANG.tsv holds, one per line, a text the framework writes in English, a tab, and the same text in
LANG: a heading, a sentence of the help, the purpose of a built-in, or the template of an error message
with its printf conversions, which the translation keeps in the same order. In both columns \\n is a
newline, \\t a tab and \\\\ a backslash. From it this script writes c/src/i18n_LANG.c, the table the C
library is built with, and the block between the two markers of python/maelys_cli.py and of
tools/maelys-cli-man, so that C, Python and the manual page read the same data.

    python3 scripts/i18n.py            check: exit 1 when a table is invalid or a generated file is stale
    python3 scripts/i18n.py --write    write the generated files
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANGUAGES = ("fr",)
PYTHON = (ROOT / "python" / "maelys_cli.py", ROOT / "tools" / "maelys-cli-man")
BEGIN = "# BEGIN translations generated by scripts/i18n.py from i18n/*.tsv: edit those files.\n"
END = "# END translations\n"
CONVERSION = re.compile(r"%(?:%|[-+ #0]*(?:\*|[0-9]*)(?:\.(?:\*|[0-9]*))?[hljztL]*[diuoxXcspfFeEgGaA])")


def unescape(field: str) -> str:
    return re.sub(r"\\(n|t|\\)", lambda m: {"n": "\n", "t": "\t", "\\": "\\"}[m.group(1)], field)


def conversions(text: str) -> list:
    return [m.group(0) for m in CONVERSION.finditer(text) if m.group(0) != "%%"]


def read(language: str) -> list:
    path = ROOT / "i18n" / f"{language}.tsv"
    entries, seen, problems = [], set(), []
    for number, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        where = f"{path.relative_to(ROOT)}:{number}"
        if len(fields) != 2 or not fields[0] or not fields[1]:
            problems.append(f"{where}: a line is a source, a tab and its translation")
            continue
        source, text = unescape(fields[0]), unescape(fields[1])
        if source in seen:
            problems.append(f"{where}: {source!r} is translated twice")
        seen.add(source)
        if "%" in source.replace("%%", "") and not conversions(source):
            problems.append(f"{where}: a '%' that is not a conversion")
        if conversions(source) != conversions(text):
            problems.append(f"{where}: the translation keeps {conversions(text)}, the source has {conversions(source)}")
        if any(ord(c) < 0x20 and c not in "\n" for c in source + text):
            problems.append(f"{where}: a control character")
        entries.append((source, text))
    if problems:
        raise SystemExit("\n".join(problems))
    return entries


def c_string(text: str) -> str:
    out = []
    for c in text:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif c == "?":
            out.append("\\?")      # never a trigraph
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def c_table(language: str, entries: list) -> str:
    lines = [f"/* SPDX-License-Identifier: MPL-2.0 */",
             f"/* Generated by scripts/i18n.py from i18n/{language}.tsv: edit that file, then run",
             f" * python3 scripts/i18n.py --write. The framework's own texts in {language}. */",
             '#include "internal.h"', "",
             f"static const maelys_cli_translation_t translations[] = {{"]
    for source, text in entries:
        lines.append(f"    {{{c_string(source)},")
        lines.append(f"     {c_string(text)}}},")
    lines += ["};", "",
              f"const maelys_cli_language_t maelys_cli_framework_{language} = {{",
              f'    "{language}", translations, sizeof(translations) / sizeof(translations[0]),',
              "};", ""]
    return "\n".join(lines)


def python_block(tables: dict) -> str:
    lines = [BEGIN, "_FRAMEWORK_TRANSLATIONS = {\n"]
    for language, entries in tables.items():
        lines.append(f"    {language!r}: {{\n")
        for source, text in entries:
            lines.append(f"        {source!r}:\n            {text!r},\n")
        lines.append("    },\n")
    lines.append("}\n")
    lines.append(END)
    return "".join(lines)


def main(argv: list) -> int:
    write = argv[1:] == ["--write"]
    if argv[1:] and not write:
        print(__doc__, file=sys.stderr)
        return 2
    tables = {language: read(language) for language in LANGUAGES}
    stale = []
    for language, entries in tables.items():
        path = ROOT / "c" / "src" / f"i18n_{language}.c"
        wanted = c_table(language, entries)
        if write:
            path.write_text(wanted, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != wanted:
            stale.append(str(path.relative_to(ROOT)))
    wanted = python_block(tables)
    for path in PYTHON:
        module = path.read_text(encoding="utf-8")
        start, end = module.index(BEGIN), module.index(END) + len(END)
        if write:
            path.write_text(module[:start] + wanted + module[end:], encoding="utf-8")
        elif module[start:end] != wanted:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("i18n-check: stale " + ", ".join(stale) + ": run python3 scripts/i18n.py --write", file=sys.stderr)
        return 1
    counts = ", ".join(f"{language} {len(entries)} texts" for language, entries in tables.items())
    print(f"i18n-check: ok ({counts})" if not write else f"i18n: written ({counts})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
